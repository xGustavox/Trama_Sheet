import { readFileSync, writeFileSync } from 'node:fs'

const catalog = JSON.parse(readFileSync(new URL('../src/lib/equipment-catalog.json', import.meta.url), 'utf8'))
const quote = value => `'${value.replaceAll("'", "''")}'`
const items = catalog.items.map(item => `(${quote(item.id)}, ${quote(item.name)}, ${quote(item.category)}, ${quote(item.subcategory)}, ${quote(JSON.stringify(item))}::jsonb)`).join(',\n')
const packs = catalog.packs.map(pack => `(${quote(pack.id)}, ${quote(pack.name)}, ${pack.priceCp}, ${pack.sourcePage})`).join(',\n')
const contents = catalog.packs.flatMap(pack => pack.items.map(item => `(${quote(pack.id)}, ${quote(item.itemId)}, ${item.quantity})`)).join(',\n')
const components = catalog.items.flatMap(kit => (kit.components ?? []).map(item => `(${quote(kit.id)}, ${quote(item.itemId)}, ${item.quantity ?? 'NULL'})`)).join(',\n')
const sql = `-- Generated by npm run equipment:seed from src/lib/equipment-catalog.json.
-- Only regenerate this initial migration before it is applied; use a new migration thereafter.
BEGIN;

CREATE TABLE public.equipment_items (
  id text PRIMARY KEY,
  name text NOT NULL,
  category text NOT NULL CHECK (category IN ('armor', 'weapons', 'tools', 'instruments', 'gear')),
  subcategory text NOT NULL,
  data jsonb NOT NULL CHECK (data->>'id' = id AND data->>'category' = category AND data->>'subcategory' = subcategory)
);
CREATE INDEX equipment_items_category_subcategory_idx ON public.equipment_items (category, subcategory);

CREATE TABLE public.equipment_packs (
  id text PRIMARY KEY,
  name text NOT NULL,
  price_cp integer NOT NULL CHECK (price_cp >= 0),
  source_page smallint NOT NULL
);

CREATE TABLE public.equipment_pack_items (
  pack_id text NOT NULL REFERENCES public.equipment_packs(id) ON DELETE CASCADE,
  item_id text NOT NULL REFERENCES public.equipment_items(id),
  quantity integer NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (pack_id, item_id)
);

CREATE TABLE public.equipment_item_components (
  kit_item_id text NOT NULL REFERENCES public.equipment_items(id) ON DELETE CASCADE,
  item_id text NOT NULL REFERENCES public.equipment_items(id),
  quantity integer CHECK (quantity IS NULL OR quantity > 0),
  PRIMARY KEY (kit_item_id, item_id),
  CHECK (kit_item_id <> item_id)
);

INSERT INTO public.equipment_items (id, name, category, subcategory, data) VALUES
${items};

INSERT INTO public.equipment_packs (id, name, price_cp, source_page) VALUES
${packs};

INSERT INTO public.equipment_pack_items (pack_id, item_id, quantity) VALUES
${contents};

INSERT INTO public.equipment_item_components (kit_item_id, item_id, quantity) VALUES
${components};

ALTER TABLE public.equipment_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.equipment_packs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.equipment_pack_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.equipment_item_components ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Equipment items are publicly readable" ON public.equipment_items FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Equipment packs are publicly readable" ON public.equipment_packs FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Equipment pack items are publicly readable" ON public.equipment_pack_items FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Equipment kit components are publicly readable" ON public.equipment_item_components FOR SELECT TO anon, authenticated USING (true);
GRANT SELECT ON public.equipment_items, public.equipment_packs, public.equipment_pack_items, public.equipment_item_components TO anon, authenticated;

COMMIT;
`
const path = new URL('../supabase/migrations/20260926160000_equipment_catalog.sql', import.meta.url)
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== sql) throw new Error('Catálogo e migração divergentes. Execute npm run equipment:seed.')
} else writeFileSync(path, sql)
